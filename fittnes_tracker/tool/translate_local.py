# ── Translation logic ─────────────────────────────────────────────────────────

def translate_name(name: str) -> str:
    if name in MANUAL_OVERRIDES:
        return MANUAL_OVERRIDES[name]

    result = name
    # Apply phrase map in order (longest first already, but also sort by len desc)
    for eng, de in PHRASE_MAP:
        # Whole-word / phrase replacement, case-insensitive
        pattern = r'(?<![A-Za-z])' + re.escape(eng) + r'(?![A-Za-z])'
        result = re.sub(pattern, de, result, flags=re.IGNORECASE)

    return result


def translate_description(desc: str) -> str | None:
    """
    Build a brief German description from key terms in the English text.
    For most exercises a template based on the translated name is good enough.
    """
    if not desc:
        return None
    # Keep it short — just note it's an exercise and translate main nouns
    result = desc
    for eng, de in PHRASE_MAP:
        pattern = r'(?<![A-Za-z])' + re.escape(eng) + r'(?![A-Za-z])'
        result = re.sub(pattern, de, result, flags=re.IGNORECASE)
    # Trim to a reasonable length
    if len(result) > 300:
        result = result[:300].rsplit(' ', 1)[0] + '...'
    return result


# ── Helpers ──────────────────────────────────────────────────────────────────

def parse_json_list(raw: str) -> list:
    try:
        r = json.loads(raw)
        return r if isinstance(r, list) else []
    except Exception:
        return []

def build_description(instructions_raw: str) -> str:
    steps = parse_json_list(instructions_raw)
    if not steps:
        return ''
    text = ' '.join(str(s).strip() for s in steps)
    return text[:400].rsplit(' ', 1)[0] + '...' if len(text) > 400 else text


