if __name__ == '__main__':
    script_dir = os.path.dirname(os.path.abspath(__file__))
    root = os.path.join(script_dir, '..')
    csv_path   = os.path.join(root, 'exercises', 'exercises.csv')
    cache_path = os.path.join(script_dir, 'translations_de.json')

    with open(csv_path, newline='', encoding='utf-8') as f:
        rows = list(csv.DictReader(f.read().lstrip('\n').splitlines()))

    cache: dict = {}
    if os.path.exists(cache_path):
        with open(cache_path, encoding='utf-8') as f:
            cache = json.load(f)

    added = 0
    for row in rows:
        name = row['name'].strip()
        if name in cache:
            continue
        desc_en = build_description(row.get('instructions', '[]'))
        name_de = translate_name(name)
        desc_de = translate_description(desc_en)
        cache[name] = {'nameDe': name_de, 'descriptionDe': desc_de}
        added += 1

    with open(cache_path, 'w', encoding='utf-8') as f:
        json.dump(cache, f, ensure_ascii=False, indent=2)

    print(f'Translated {added} new exercises. Total cache: {len(cache)}.')
    print(f'Output: {cache_path}')
    print('Now run: python3 tool/generate_seeds.py')
